// Your goals are simple:

// Pass the screen: Show you're professional and relevant.

// Gather information: Decide if you even want the job.

// Schedule the interview: Get to the next step.

// Here are the important sentences and questions you'll hear, how to reply, and what you should ask.

// 1. The Opening & Confirmation
// What they say:

// "Hi, is this [Your Name]? This is [Recruiter's Name] calling from [Company Name] about the application you submitted for the [Job Title] position."

// How to reply:

// Be professional and enthusiastic.

// "Yes, this is [Your Name]. Hello [Recruiter's Name], thank you so much for calling! Yes, I absolutely remember applying for that role."

// 2. The "Tell Me About Yourself" Question (Very Common)
// What they say:

// "Can you walk me through your resume?" or "Tell me a little about yourself and your background."

// How to reply (The 60-Second Pitch):

// Don't just recite your resume. Structure your answer.

// Present: "I'm currently a [Your Current Title] at [Current Company], where my main focus is on [2-3 key technologies, e.g., React, Node.js, and MongoDB]."

// Past: "Before this, I was at [Previous Company] where I worked on [mention a relevant achievement, e.g., building a full-stack application]."

// Future: "I'm really excited about the opportunity at [Their Company] because I saw you use [mention a tech from the job description], which aligns perfectly with my skills and what I'm looking to do next."

// Example:

// "I'm currently a Full-Stack Developer at TechCorp, where I spend most of my time building user interfaces with React and supporting them with Node.js APIs. Previously, at StartupX, I was responsible for designing and integrating the MongoDB database for our main product. I'm really interested in this role because I saw you're using a modern MERN stack, which is a great fit for my experience."

// 3. The "Why Are You Interested?" Question
// What they say:

// "What do you know about our company?" or "Why are you interested in this role?"

// How to reply:

// Show you've done your homework. Mention something specific.
  
// "I've been following [Company Name] for a while and I'm really impressed with your product, especially the [mention a specific feature]. I also saw on your blog that you're working on [mention a project or tech], which is very exciting."

// "This role specifically caught my eye because the job description emphasized [mention a key requirement, e.g., 'building scalable APIs' or 'optimizing front-end performance'], which is an area I'm very passionate about and have experience in."



 
// 4. Logistics & Availability Questions
// What they say:

// "What is your current salary?" or "What are your salary expectations?"
// "What is your notice period with your current employer?"
// "Are you available for an interview next week?"

// How to reply:

// For Salary:

// Best strategy: Deflect politely to avoid low-balling yourself.

// "My expectations are aligned with the market rate for this role and my level of experience. I'm sure we can find a number that's fair once we get further into the process.
//  Could you share the salary band budgeted for this position?"

// If pressed, give a wide range based on your research on Glassdoor/Levels.fyi.

// For Notice Period:

// Be honest. "My standard notice period is [2 weeks / 1 month]. I'm committed to a smooth transition at my current role."

// For Availability:

// Be positive and flexible. "Yes, my schedule is fairly flexible next week. I can make time to speak with the team."





// Crucial Questions YOU MUST Ask Them
// This shows you're engaged and serious. Have 2-3 of these ready.

// 1. About the Role:

// "Could you tell me a little more about the day-to-day responsibilities of this role?"
// "What are the biggest challenges the person in this position would face in the first 3 months?"

// 2. About the Team:

// "Can you describe the team I would be working with? (e.g., size, structure, other roles)"
// "Who would be the hiring manager for this role?"

// 3. About the Process:

// "Could you outline the next steps in the interview process?"
// "How many interview rounds should I expect, and who would I be meeting with?"



